export function getTalentIndicatorCount() {
  return TALENT_COMPETENCIES.reduce((sum, c) => sum + c.indicators.length, 0);
}

// Flat list of all 28 indicator ids, in a stable order — used to validate
// that a submitted assessment covers every indicator (both client-side and
// server-side in api/talent-task-save.mjs).
export function getAllTalentIndicatorIds() {
  return TALENT_COMPETENCIES.flatMap(c => c.indicators.map(i => i.id));
}
